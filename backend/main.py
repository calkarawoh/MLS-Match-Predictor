from __future__ import annotations

import os
import sys
from pathlib import Path
from typing import Any

from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

import joblib
import mls_live_data
import real_model

app = FastAPI(
    title="MLS Match Predictor API",
    description="API for real-score MLS match predictions and fixture snapshots.",
    version="1.0.0",
)

allowed_origins = [
    item.strip()
    for item in os.getenv(
        "FRONTEND_ORIGINS",
        "http://localhost:5173,http://127.0.0.1:5173",
    ).split(",")
    if item.strip()
]

app.add_middleware(
    CORSMiddleware,
    allow_origins=allowed_origins,
    allow_credentials=False,
    allow_methods=["GET", "POST"],
    allow_headers=["Content-Type"],
)

history = None
team_history: dict[str, list[dict[str, Any]]] = {}
model_bundle: dict[str, Any] | None = None
startup_error: str | None = None


class PredictionRequest(BaseModel):
    home_team: str = Field(min_length=1, max_length=120)
    away_team: str = Field(min_length=1, max_length=120)


def load_app_state() -> None:
    """Load the local MLS history and trusted model generated by this project."""
    global history, team_history, model_bundle, startup_error

    try:
        history = real_model.load_matches()
        team_history = real_model.team_histories(history)
        startup_error = None
    except Exception as exc:
        history = None
        team_history = {}
        startup_error = f"Could not load MLS match history: {exc}"
        model_bundle = None
        return

    if real_model.MODEL.exists():
        try:
            # Only load a model generated locally by this project.
            model_bundle = joblib.load(real_model.MODEL)
        except Exception as exc:
            model_bundle = None
            startup_error = f"Could not load the trained model: {exc}"
    else:
        model_bundle = None


@app.on_event("startup")
def startup() -> None:
    load_app_state()


@app.get("/api/health")
def health() -> dict[str, Any]:
    return {
        "status": "ok" if history is not None else "degraded",
        "history_loaded": history is not None,
        "matches_loaded": 0 if history is None else int(len(history)),
        "model_loaded": model_bundle is not None,
        "model_source": None if model_bundle is None else model_bundle.get("source"),
        "last_scoreboard_check_utc": mls_live_data.load_snapshot().get("updated_utc"),
        "message": startup_error,
    }


@app.get("/api/teams")
def teams() -> dict[str, Any]:
    if history is None:
        raise HTTPException(status_code=503, detail=startup_error or "Match history is unavailable.")

    results = []
    for name, games in sorted(team_history.items()):
        if len(games) < 3:
            continue
        stats = real_model.team_stats(games, real_model.WINDOW)
        results.append({
            "name": name,
            "form": [game["form"] for game in games[-5:][::-1]],
            "goals_for_per_match": round(float(stats["gf"]), 2),
            "goals_against_per_match": round(float(stats["ga"]), 2),
            "points_per_match": round(float(stats["points"]), 2),
            "completed_games": len(games),
        })
    return {"teams": results, "count": len(results)}


@app.get("/api/fixtures")
def fixtures() -> dict[str, Any]:
    try:
        snapshot = mls_live_data.load_snapshot()
    except Exception as exc:
        raise HTTPException(status_code=503, detail=f"Could not read fixture snapshot: {exc}") from exc

    return {
        "updated_utc": snapshot.get("updated_utc"),
        "events": snapshot.get("events", []),
        "source_note": "Unofficial ESPN public feed. Availability and coverage are not guaranteed.",
    }


@app.post("/api/predict")
def predict(request: PredictionRequest) -> dict[str, Any]:
    if request.home_team == request.away_team:
        raise HTTPException(status_code=400, detail="Choose two different teams.")
    if history is None:
        raise HTTPException(status_code=503, detail=startup_error or "MLS history is unavailable.")
    if model_bundle is None:
        raise HTTPException(
            status_code=503,
            detail="The real-MLS model is not available. Run `python real_model.py train` from the project folder.",
        )

    available = set(team_history)
    if request.home_team not in available or request.away_team not in available:
        raise HTTPException(status_code=400, detail="One or both selected teams are not in the current match history.")

    try:
        probabilities = real_model.predict(request.home_team, request.away_team, model_bundle)
    except Exception as exc:
        raise HTTPException(status_code=422, detail=str(exc)) from exc

    labels = {0: "Away win", 1: "Draw", 2: "Home win"}
    top_code = max(probabilities, key=probabilities.get)
    return {
        "home_team": request.home_team,
        "away_team": request.away_team,
        "probabilities": {
            "away_win": round(float(probabilities.get(0, 0.0)), 6),
            "draw": round(float(probabilities.get(1, 0.0)), 6),
            "home_win": round(float(probabilities.get(2, 0.0)), 6),
        },
        "top_prediction": labels[top_code],
        "model_source": model_bundle.get("source", "Real completed MLS scores"),
        "test_season": model_bundle.get("test_year"),
        "note": "Model estimates from prior completed match scores; not guaranteed outcomes or betting odds.",
    }


@app.post("/api/reload")
def reload_data() -> dict[str, Any]:
    """Reload local files after a trusted local data sync or model retraining."""
    load_app_state()
    if history is None:
        raise HTTPException(status_code=503, detail=startup_error or "Could not reload match history.")
    return {
        "history_loaded": True,
        "matches_loaded": int(len(history)),
        "model_loaded": model_bundle is not None,
        "message": "Local history and model reloaded.",
    }


# Logos are optional. The source is ESPN's unofficial team directory;
# its availability and permission to display images publicly are not guaranteed.
# For a public deployment, confirm permitted use or provide licensed assets.
from functools import lru_cache
import re
import requests


def _normalise_team(name: str) -> str:
    return re.sub(r"[^a-z0-9]", "", str(name).casefold())


@lru_cache(maxsize=1)
def _provider_team_crests() -> dict[str, str]:
    try:
        with requests.Session() as session:
            payload = mls_live_data.fetch_json(session, "teams", {"limit": 100})
        sports = payload.get("sports") or []
        leagues = (sports[0].get("leagues") or []) if sports else []
        wrappers = (leagues[0].get("teams") or []) if leagues else []
        found: dict[str, str] = {}
        for entry in wrappers:
            team = entry.get("team") or entry
            logo_sources = team.get("logos") or []
            href = logo_sources[0].get("href") if logo_sources else team.get("logo")
            # Only display images from the expected ESPN CDN; do not pass through arbitrary URLs.
            if not isinstance(href, str) or not href.startswith(("https://a.espncdn.com/", "https://cdn.espn.com/")):
                continue
            for key in ("displayName", "shortDisplayName", "name"):
                name = team.get(key)
                if name:
                    found[_normalise_team(name)] = href
        return found
    except (RuntimeError, KeyError, IndexError, AttributeError, TypeError):
        return {}


@app.get("/api/team-logos")
def team_logos() -> dict[str, Any]:
    provider_logos = _provider_team_crests()
    mapping: dict[str, str] = {}
    for team in team_history.keys():
        key = _normalise_team(team)
        found = provider_logos.get(key)
        # Match suffix changes such as 'FC' only when there is a unique candidate.
        if found is None:
            matches = [url for candidate, url in provider_logos.items()
                       if candidate.startswith(key) or key.startswith(candidate)]
            if len(set(matches)) == 1:
                found = matches[0]
        if found:
            mapping[team] = found
    return {"logos": mapping, "matched_count": len(mapping),
            "source_note": "Unofficial ESPN team logo URLs; verify permitted use before public hosting."}
